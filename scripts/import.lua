-- Imports TandemDB loot from saved-variables files into the repo's data directory.
-- Usage: lua scripts/import.lua <data-dir> <locale> <contributor-id> <saved-variables-file> [<locale> <id> <file> ...]
-- Each file overwrites <data-dir>/contributions/<id>.lua; <data-dir>/loot.lua is then rebuilt from every
-- contribution. Saved-variables and contribution files run in an empty environment with an instruction budget.
local scriptDir = arg[0]:gsub("[^/]*$", "")

local MAX_COORDS = 5
local BUDGET = 100000000 -- instructions a data file may run; a WoW SV file needs a small fraction of this
local LOOT_FIELDS = { "item", "kind", "id", "map", "count" }

-- LuaJIT's compiled loops skip count hooks, which would let a data file run forever.
local luajit = rawget(_G, "jit")
if luajit then
    luajit.off()
end

local function fail(msg)
    io.stderr:write("import: " .. msg .. "\n")
end

local function quote(s)
    return "'" .. s:gsub("'", "'\\''") .. "'"
end

-- Loads Tandem/Store.lua for its validation; the repo's own file, so it runs unsandboxed.
local function loadStore()
    local ns = {}
    assert(loadfile(scriptDir .. "../Tandem/Store.lua"))("Tandem", ns)
    return ns.Store
end
local Store = loadStore()

-- Runs a data file in an empty environment; returns that environment and the chunk's return value,
-- or nil and an error. Binary chunks are refused; a file that runs too long is stopped.
local function sandbox(path)
    local env = {}
    local chunk, err
    if setfenv then
        local f = io.open(path, "rb")
        if f and f:read(1) == "\27" then
            f:close()
            return nil, path .. ": binary chunks are not accepted"
        end
        if f then
            f:close()
        end
        chunk, err = loadfile(path)
        if chunk then
            setfenv(chunk, env)
        end
    else
        chunk, err = loadfile(path, "t", env)
    end
    if not chunk then
        return nil, err:find(path, 1, true) and err or path .. ": " .. err
    end
    local steps = 0
    debug.sethook(function()
        steps = steps + 1
        if steps * 1000000 >= BUDGET then
            error("ran over its instruction budget", 2)
        end
    end, "", 1000000)
    local ok, result = pcall(chunk)
    debug.sethook()
    if not ok then
        return nil, path .. ": " .. tostring(result)
    end
    return env, result
end

-- Validates loot and npcs through Store.Load; returns the clean copies and the number of dropped entries.
local function clean(loot, npcs)
    local db, report = Store.Load({ schemaVersion = 1, loot = loot, npcs = npcs })
    return db.loot, db.npcs, report.dropped
end

-- Writer: keys sorted (numbers numerically before strings lexically), one entry per line.
local function sortedKeys(t)
    local keys = {}
    for k in pairs(t) do
        keys[#keys + 1] = k
    end
    table.sort(keys, function(a, b)
        local ta, tb = type(a), type(b)
        if ta ~= tb then
            return ta == "number"
        end
        return a < b
    end)
    return keys
end

local function scalar(v)
    if type(v) == "number" then
        return string.format("%d", v)
    end
    return string.format("%q", v)
end

local function key(k)
    return "[" .. scalar(k) .. "]"
end

local function lootEntry(e)
    local parts = {}
    for _, field in ipairs(LOOT_FIELDS) do
        parts[#parts + 1] = field .. " = " .. scalar(e[field])
    end
    local coords = {}
    for _, c in ipairs(e.coords) do
        coords[#coords + 1] = "{ " .. scalar(c[1]) .. ", " .. scalar(c[2]) .. " }"
    end
    parts[#parts + 1] = "coords = {" .. (#coords > 0 and " " .. table.concat(coords, ", ") .. " " or "") .. "}"
    return "{ " .. table.concat(parts, ", ") .. " }"
end

local function block(out, indent, name, t, format)
    out[#out + 1] = indent .. name .. " = {"
    for _, k in ipairs(sortedKeys(t)) do
        out[#out + 1] = indent .. "    " .. key(k) .. " = " .. format(t[k]) .. ","
    end
    out[#out + 1] = indent .. "},"
end

local function writeFile(path, out)
    local tmp = path .. ".tmp"
    local f, err = io.open(tmp, "wb")
    if not f then
        return nil, err
    end
    f:write(table.concat(out, "\n"), "\n")
    f:close()
    local ok, rerr = os.rename(tmp, path)
    if not ok then
        os.remove(tmp)
        return nil, rerr
    end
    return true
end

local function writeContribution(path, locale, loot, npcs)
    local out = {
        "-- Loot snapshot of one account, generated by `make import`; do not edit.",
        "return {",
        "    locale = " .. scalar(locale) .. ",",
    }
    block(out, "    ", "loot", loot, lootEntry)
    block(out, "    ", "npcs", npcs, scalar)
    out[#out + 1] = "}"
    return writeFile(path, out)
end

local function contributionFiles(dir)
    local files = {}
    local p = io.popen("ls " .. quote(dir) .. " 2>/dev/null")
    for name in p:lines() do
        if name:match("^[%w_-]+%.lua$") then
            files[#files + 1] = name
        end
    end
    p:close()
    table.sort(files)
    return files
end

-- Rebuilds loot.lua from every contribution; returns the number of contributions used.
local function rebuild(dataDir)
    local dir = dataDir .. "/contributions"
    local loot, names, contributors = {}, {}, 0
    for _, name in ipairs(contributionFiles(dir)) do
        local _, c = sandbox(dir .. "/" .. name)
        if type(c) ~= "table" or type(c.locale) ~= "string" or not c.locale:match("^%a%a%a%a$") then
            fail(dir .. "/" .. name .. ": not a contribution, skipped")
        else
            local cLoot, cNpcs, dropped = clean(c.loot, c.npcs)
            if dropped > 0 then
                fail(("%s/%s: %d invalid entries ignored"):format(dir, name, dropped))
            end
            contributors = contributors + 1
            for k, e in pairs(cLoot) do
                local agg = loot[k]
                if not agg then
                    agg = { item = e.item, kind = e.kind, id = e.id, map = e.map, count = 0, coords = {}, seen = {} }
                    loot[k] = agg
                end
                agg.count = agg.count + e.count
                for _, xy in ipairs(e.coords) do
                    local ck = xy[1] .. "," .. xy[2]
                    if not agg.seen[ck] then
                        agg.seen[ck] = true
                        agg.coords[#agg.coords + 1] = { xy[1], xy[2] }
                    end
                end
            end
            local localeNames = names[c.locale] or {}
            names[c.locale] = localeNames
            for npc, n in pairs(cNpcs) do
                if not localeNames[npc] or n < localeNames[npc] then
                    localeNames[npc] = n
                end
            end
        end
    end

    for _, agg in pairs(loot) do
        agg.seen = nil
        table.sort(agg.coords, function(a, b)
            return a[1] < b[1] or (a[1] == b[1] and a[2] < b[2])
        end)
        for i = #agg.coords, MAX_COORDS + 1, -1 do
            agg.coords[i] = nil
        end
    end

    local out = {
        "-- Loot sources merged from data/contributions/, generated by `make import`; do not edit.",
        "return {",
        "    contributors = " .. scalar(contributors) .. ",",
    }
    block(out, "    ", "loot", loot, lootEntry)
    out[#out + 1] = "    names = {"
    for _, locale in ipairs(sortedKeys(names)) do
        block(out, "        ", key(locale), names[locale], scalar)
    end
    out[#out + 1] = "    },"
    out[#out + 1] = "}"
    local ok, err = writeFile(dataDir .. "/loot.lua", out)
    if not ok then
        fail(err)
        return nil
    end
    return contributors
end

-- Imports one saved-variables file; returns true when its contribution was written.
local function import(dataDir, locale, id, path)
    if not locale:match("^%a%a%a%a$") then
        fail(path .. ": invalid locale " .. locale .. ", skipped")
        return false
    end
    if not id:match("^[%w_-]+$") then
        fail(path .. ": invalid contributor id " .. id .. ", skipped")
        return false
    end
    local env, err = sandbox(path)
    if not env then
        fail(err .. ", skipped")
        return false
    end
    if type(env.TandemDB) ~= "table" then
        fail(path .. ": no TandemDB table, skipped")
        return false
    end
    local db, report = Store.Load(env.TandemDB)
    if report.status == "newer" then
        fail(("%s: schemaVersion %s is newer than this importer, skipped"):format(path, tostring(report.version)))
        return false
    end
    local loot, npcs = db.loot, db.npcs
    if report.dropped > 0 then
        fail(("%s: %d invalid entries ignored"):format(path, report.dropped))
    end

    local dest = dataDir .. "/contributions/" .. id .. ".lua"
    local ok, werr = writeContribution(dest, locale, loot, npcs)
    if not ok then
        fail(werr)
        return false
    end
    local nLoot, nNpcs = 0, 0
    for _ in pairs(loot) do
        nLoot = nLoot + 1
    end
    for _ in pairs(npcs) do
        nNpcs = nNpcs + 1
    end
    print(("wrote %s (%s: %d loot entries, %d npc names)"):format(dest, locale, nLoot, nNpcs))
    return true
end

local dataDir = arg[1]
if not dataDir or #arg < 4 or (#arg - 1) % 3 ~= 0 then
    fail("usage: lua scripts/import.lua <data-dir> <locale> <contributor-id> <saved-variables-file> ...")
    os.exit(2)
end
os.execute("mkdir -p " .. quote(dataDir .. "/contributions"))

local imported = 0
for i = 2, #arg, 3 do
    if import(dataDir, arg[i], arg[i + 1], arg[i + 2]) then
        imported = imported + 1
    end
end
if imported == 0 then
    fail("no file imported")
    os.exit(1)
end
local contributors = rebuild(dataDir)
if not contributors then
    os.exit(1)
end
print(("wrote %s/loot.lua (%d contributors)"):format(dataDir, contributors))
